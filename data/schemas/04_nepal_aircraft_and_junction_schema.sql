-- ------------------------------------------------------------------------------
-- 3. JUNCTION TABLE: nepal_aircraft_specifications
-- Connects individual Nepal registered airframes (tail numbers) with their
-- aerodynamic, engineering, weight, and performance specifications in aircraft_specifications.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.nepal_aircraft_specifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nepal_aircraft_id BIGINT NOT NULL REFERENCES public.nepal_aircraft(id) ON DELETE CASCADE,
    specification_id BIGINT NOT NULL REFERENCES public.aircraft_specifications(id) ON DELETE CASCADE,
    match_method VARCHAR(50) DEFAULT 'typecode_match' NOT NULL, -- 'exact_typecode', 'model_variant', 'iata_mapping', 'manual_verified'
    match_confidence NUMERIC(3, 2) DEFAULT 1.00 NOT NULL,       -- Confidence score (0.00 - 1.00)
    is_primary BOOLEAN DEFAULT TRUE NOT NULL,                   -- Flag indicating the primary baseline specification
    notes TEXT,                                                 -- Detailed mapping / variant notes
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL,
    CONSTRAINT uq_nepal_aircraft_specification UNIQUE (nepal_aircraft_id, specification_id)
);

-- Indexes for junction lookups
CREATE INDEX IF NOT EXISTS idx_nas_nepal_aircraft_id ON public.nepal_aircraft_specifications (nepal_aircraft_id);
CREATE INDEX IF NOT EXISTS idx_nas_specification_id ON public.nepal_aircraft_specifications (specification_id);
CREATE INDEX IF NOT EXISTS idx_nas_composite ON public.nepal_aircraft_specifications (nepal_aircraft_id, specification_id);

