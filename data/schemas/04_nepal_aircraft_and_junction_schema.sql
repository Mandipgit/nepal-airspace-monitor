-- ------------------------------------------------------------------------------
-- 1. NEPAL AIRCRAFT TABLE
-- Stores full registry data for aircraft registered in Nepal (9N-xxx / NA-xxx).
-- Sourced from Nepal-aricraft-dataset.csv.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.nepal_aircraft (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    icao24 VARCHAR(10) UNIQUE NOT NULL,                       -- 24-bit Mode-S transponder hex address (e.g. '70a00d')
    registration VARCHAR(20),                                 -- Nepalese tail registration mark (e.g. '9N-AIH', 'NA-058')
    typecode VARCHAR(10),                                     -- ICAO aircraft type designator (e.g. 'AT75', 'DH8D', 'A320', 'AS50')
    model TEXT,                                               -- Manufacturer/commercial model name (e.g. 'ATR 72-500', 'Dash 8-400')
    manufacturer_name TEXT,                                   -- Manufacturer name (e.g. 'Avions De Transport Regional', 'British Aerospace')
    manufacturer_icao TEXT,                                   -- Manufacturer ICAO identifier (e.g. 'ATR', 'AIRBUS', 'BOEING')
    operator TEXT,                                            -- Operating airline/company (e.g. 'Buddha Air', 'Yeti Airlines')
    operator_callsign TEXT,                                   -- Carrier telephony callsign (e.g. 'BUDDHA AIR', 'YETI AIRLINES')
    operator_icao VARCHAR(10),                                -- 3-letter ICAO carrier code (e.g. 'BHA', 'NYT', 'RNA')
    operator_iata VARCHAR(10),                                -- 2-letter IATA carrier code (e.g. 'U4', 'YT', 'RA')
    owner TEXT,                                               -- Legal owner/lessor (e.g. 'Buddha Air', 'Yeti Airlines')
    serial_number VARCHAR(50),                                -- Manufacturer Serial Number (MSN)
    icao_aircraft_class VARCHAR(10),                          -- ICAO aircraft class (e.g. 'L2T', 'L2J', 'H1T', 'H2T')
    category_description TEXT,                                -- Emitter / weight category description
    country VARCHAR(50) DEFAULT 'Nepal',                      -- Country of registration
    engines TEXT,                                             -- Installed powerplant description (e.g. 'PWC PW127F')
    built_year VARCHAR(20),                                   -- Year or date built
    first_flight_date DATE,                                   -- Date of maiden flight
    first_seen TIMESTAMPTZ,                                   -- First detected timestamp
    recorded_timestamp TIMESTAMPTZ,                           -- Snapshot timestamp
    registered_date DATE,                                     -- Date registered with Civil Aviation Authority of Nepal (CAAN)
    reg_until DATE,                                           -- Registration certificate expiry date
    status VARCHAR(50),                                       -- Operational / airworthiness status
    modes BOOLEAN DEFAULT FALSE,                              -- Mode-S transponder operational
    adsb BOOLEAN DEFAULT FALSE,                               -- ADS-B Out operational
    acars BOOLEAN DEFAULT FALSE,                              -- ACARS operational
    vdl BOOLEAN DEFAULT FALSE,                                -- VDL Mode 2 operational
    notes TEXT,                                               -- Additional operational notes or remarks
    sel_cal VARCHAR(20),                                      -- Selective Calling (SELCAL) code
    line_number VARCHAR(50),                                  -- Assembly line sequence number
    prev_reg VARCHAR(50),                                     -- Previous foreign registration mark
    next_reg VARCHAR(50),                                     -- Subsequent registration mark if exported
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL
);

-- Indexes for high-frequency queries
CREATE INDEX IF NOT EXISTS idx_nepal_aircraft_icao24 ON public.nepal_aircraft (icao24);
CREATE INDEX IF NOT EXISTS idx_nepal_aircraft_reg ON public.nepal_aircraft (registration);
CREATE INDEX IF NOT EXISTS idx_nepal_aircraft_typecode ON public.nepal_aircraft (typecode);
CREATE INDEX IF NOT EXISTS idx_nepal_aircraft_operator ON public.nepal_aircraft (operator);
CREATE INDEX IF NOT EXISTS idx_nepal_aircraft_operator_icao ON public.nepal_aircraft (operator_icao);

