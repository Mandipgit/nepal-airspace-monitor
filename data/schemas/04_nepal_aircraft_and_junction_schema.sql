-- ------------------------------------------------------------------------------
-- 5. AUTOMATIC POPULATION PROCEDURE FOR JUNCTION TABLE
-- Runs an intelligent match linking every possible Nepal aircraft to
-- its matching specification row(s) in aircraft_specifications.
-- ------------------------------------------------------------------------------
INSERT INTO public.nepal_aircraft_specifications (nepal_aircraft_id, specification_id, match_method, match_confidence, is_primary, notes)
SELECT 
    na.id AS nepal_aircraft_id,
    s.id AS specification_id,
    CASE 
        WHEN UPPER(s.icao_type) = UPPER(na.typecode) THEN 'exact_typecode'
        WHEN UPPER(s.icao_type) = 'AT7' AND na.typecode = 'AT75' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = 'AT4' AND na.typecode = 'AT43' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = 'DH4' AND na.typecode = 'DH8D' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = 'J41' AND na.typecode = 'JS41' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = 'CR2' AND na.typecode = 'CRJ2' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = 'CR7' AND na.typecode = 'CRJ7' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = '320' AND na.typecode = 'A320' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = '319' AND na.typecode = 'A319' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = '332' AND na.typecode = 'A332' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = '752' AND na.typecode = 'B752' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = 'BE1' AND na.typecode = 'B190' THEN 'iata_mapping'
        WHEN UPPER(s.icao_type) = 'D28' AND na.typecode IN ('D228', 'D28D') THEN 'iata_mapping'
        ELSE 'model_variant'
    END AS match_method,
    1.00 AS match_confidence,
    TRUE AS is_primary,
    CONCAT('Matched tail ', na.registration, ' (typecode: ', na.typecode, ') with specification ', s.model, ' [', s.icao_type, ']') AS notes
FROM public.nepal_aircraft na
JOIN public.aircraft_specifications s ON (
    -- 1. Exact ICAO code match
    UPPER(s.icao_type) = UPPER(na.typecode)
    -- 2. Standard ICAO/IATA designator cross-reference
    OR (na.typecode = 'AT75' AND s.icao_type = 'AT7' AND s.model ILIKE '%72-500%')
    OR (na.typecode = 'AT43' AND s.icao_type = 'AT4' AND s.model ILIKE '%42-320%')
    OR (na.typecode = 'DH8D' AND s.icao_type = 'DH4')
    OR (na.typecode = 'JS41' AND (s.icao_type = 'J41' OR s.model ILIKE '%Jetstream41%'))
    OR (na.typecode = 'CRJ2' AND s.icao_type = 'CR2')
    OR (na.typecode = 'CRJ7' AND s.icao_type = 'CR7')
    OR (na.typecode = 'A320' AND s.icao_type = '320')
    OR (na.typecode = 'A319' AND s.icao_type = '319')
    OR (na.typecode = 'A332' AND s.icao_type = '332')
    OR (na.typecode = 'B752' AND s.icao_type = '752')
    OR (na.typecode = 'B190' AND s.icao_type = 'BE1')
    OR (na.typecode IN ('D228', 'D28D') AND s.icao_type = 'D28')
)
ON CONFLICT (nepal_aircraft_id, specification_id) DO NOTHING;
